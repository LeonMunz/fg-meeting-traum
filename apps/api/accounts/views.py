class SessionListView(APIView):
    """List the current user's active sessions.

    Only non-secret metadata is returned; the raw Django session key is
    never exposed. Expired/revoked sessions are not listed.
    """

    permission_classes = [IsAuthenticated]

    def get(self, request):
        current_session_key = request.session.session_key
        rows = list_user_sessions(request.user, current_session_key)
        return Response({
            "sessions": [
                serialize_user_session(row, current_session_key)
                for row in rows
            ],
        })


class SessionRevokeView(APIView):
    """Revoke one session of the current user by its public id.

    Unknown ids and ids owned by another user both answer the same
    non-leaking 404. Revoking an already-revoked session is a 404.
    """

    permission_classes = [IsAuthenticated]

    def post(self, request, session_id):
        revoked = revoke_user_session(request.user, session_id)
        if not revoked:
            return Response(
                {"error": "Session not found"},
                status=404,
            )
        return Response({"detail": "Session revoked"})


